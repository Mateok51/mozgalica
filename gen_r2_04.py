def norm(s):
    s = unicodedata.normalize('NFD', s.lower())
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn').replace('đ', 'd')
    return re.sub(r'[^a-z0-9 ]', '', re.sub(r'\s+', ' ', s)).strip()

base = sys.argv[1]
merged = json.load(open(base + '/merged.json'))
seen = {norm(x['q']) for v in merged['cats'].values() for x in v}

out = {}
for cat, items, target in (("Književnost", K, 80), ("Jezici i riječi", J, 80)):
    lst = []
    for q, c, w in items:
        if norm(q) in seen:
            print('DUP', q); continue
        seen.add(norm(q))
        assert len(w) == 3 and len({c, *w}) == 4, q
        lst.append((q, c, w))
    lst = lst[:target]
    res = []
    for i, (q, c, w) in enumerate(lst):
        a = i % 4
        o = list(w); o.insert(a, c)
        if len(q) > 110: print('LONGQ', len(q), q)
        for x in o:
            if len(x) > 30: print('LONGO', x)
        res.append({"q": q, "o": o, "a": a})
    out[cat] = res
    print(cat, len(res), 'of', len(items))

json.dump({"cats": out}, open(base + '/r2_04.json', 'w'), ensure_ascii=False, indent=1)
